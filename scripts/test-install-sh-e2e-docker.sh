#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source "$ROOT_DIR/scripts/lib/docker-build.sh"
IMAGE_NAME="${NOVA_AI_INSTALL_E2E_IMAGE:-nova-ai-install-e2e:local}"
INSTALL_URL="${NOVA_AI_INSTALL_URL:-https://nova-ai.bot/install.sh}"

OPENAI_API_KEY="${OPENAI_API_KEY:-}"
ANTHROPIC_API_KEY="${ANTHROPIC_API_KEY:-}"
ANTHROPIC_API_TOKEN="${ANTHROPIC_API_TOKEN:-}"
NOVA_AI_E2E_MODELS="${NOVA_AI_E2E_MODELS:-}"

echo "==> Build image: $IMAGE_NAME"
docker_build_run install-e2e-build \
  -t "$IMAGE_NAME" \
  -f "$ROOT_DIR/scripts/docker/install-sh-e2e/Dockerfile" \
  "$ROOT_DIR/scripts/docker"

echo "==> Run E2E installer test"
docker run --rm \
  -e NOVA_AI_INSTALL_URL="$INSTALL_URL" \
  -e NOVA_AI_INSTALL_TAG="${NOVA_AI_INSTALL_TAG:-latest}" \
  -e NOVA_AI_E2E_MODELS="$NOVA_AI_E2E_MODELS" \
  -e NOVA_AI_INSTALL_E2E_OPENAI_MODEL="${NOVA_AI_INSTALL_E2E_OPENAI_MODEL:-}" \
  -e NOVA_AI_INSTALL_E2E_OPENAI_PROVIDER_TIMEOUT_SECONDS="${NOVA_AI_INSTALL_E2E_OPENAI_PROVIDER_TIMEOUT_SECONDS:-}" \
  -e NOVA_AI_INSTALL_E2E_PREVIOUS="${NOVA_AI_INSTALL_E2E_PREVIOUS:-}" \
  -e NOVA_AI_INSTALL_E2E_SKIP_PREVIOUS="${NOVA_AI_INSTALL_E2E_SKIP_PREVIOUS:-0}" \
  -e NOVA_AI_INSTALL_E2E_AGENT_TURN_TIMEOUT_SECONDS="${NOVA_AI_INSTALL_E2E_AGENT_TURN_TIMEOUT_SECONDS:-300}" \
  -e NOVA_AI_INSTALL_E2E_AGENT_TURNS_PARALLEL="${NOVA_AI_INSTALL_E2E_AGENT_TURNS_PARALLEL:-1}" \
  -e NOVA_AI_INSTALL_E2E_AGENT_TOOL_SMOKE="${NOVA_AI_INSTALL_E2E_AGENT_TOOL_SMOKE:-1}" \
  -e NOVA_AI_NO_ONBOARD=1 \
  -e OPENAI_API_KEY \
  -e ANTHROPIC_API_KEY \
  -e ANTHROPIC_API_TOKEN \
  "$IMAGE_NAME"
